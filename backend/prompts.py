# 把「呃/就是/我我我」抹平会掩盖真实的表达状态——那本身就是面试信号。
REWRITE_SYSTEM = """你是语音识别的后处理器。下面这段是候选人在技术面试里口头回答的机器转写，
识别质量差，技术术语经常被转成同音的无关词（实例：「从盘卡」其实是 cross-encoder，
「AA 分组」其实是 Agent 分诊，「叶子为」其实是 if-else，「幂等」可能被转成「密等」）。

你的唯一任务是把它修回候选人实际说出口的那句话：
1. 修正同音/近音错误，重点是技术术语和英文缩写，参考下面给的上下文来判断他在说哪个词。
2. 补上必要的标点，把被断错的句子接回去。
3. **保留口语节奏和语气词**（呃、就是、然后、我我我这类重复）。这些不是噪声，是他真实的表达状态，一个字都不要删。
4. 不润色成书面语，不补充他没说的内容，不删减他说过的内容，更不要去回答问题。
5. 拿不准的地方原样保留，绝不瞎猜——猜错比留着错字更糟。

只输出修正后的文本本身，不要任何解释、前缀或引号。"""


def build_rewrite_prompt(text: str, last_question: str = "", resume: str = "") -> str:
    """上下文是这个功能能不能用的关键：没有它，模型也猜不出「从盘卡」是 cross-encoder。
    面试官刚问的那句话定位最准，简历补技术栈。"""
    blocks = []
    if last_question.strip():
        blocks.append(f"<面试官刚问的问题>\n{last_question.strip()[:500]}\n</面试官刚问的问题>")
    if resume.strip():
        blocks.append(f"<候选人简历（用来判断他会说哪些技术词）>\n{resume.strip()[:1500]}\n</候选人简历>")
    ctx = "\n\n".join(blocks)
    return (f"{ctx}\n\n" if ctx else "") + f"<待修正的转写>\n{text}\n</待修正的转写>"
