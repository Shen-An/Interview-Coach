_PROJECT_DATE = re.compile(
    r"20\d{2}[./年-]\d{1,2}\s*(?:-|~|～|至)\s*20\d{2}[./年-]\d{1,2}"
)


def extract_resume_projects(resume: str) -> list[str]:
    """从简历中提取带起止日期的项目标题，供阶段调度使用。

    PDF/DOCX 的纯文本提取经常把「项目经历」章节标题放到项目内容之后，
    因此不能依赖章节顺序；这里只识别「项目名 — 职责/简介 日期」这类标题行。
    解析失败时返回空列表，面试仍按原有模型策略运行。
    """
    text = str(resume or "")
    if not text.strip():
        return []
    lines = [re.sub(r"[ \t]+", " ", line).strip() for line in text.splitlines()]
    out: list[str] = []
    seen: set[str] = set()
    for line in lines:
        if not line:
            continue
        date_match = _PROJECT_DATE.search(line)
        if not date_match:
            continue
        heading = line[:date_match.start()].strip(" -—–_:：")
        # 项目标题通常是「名称 — 职责/简介」；教育经历没有这个分隔符，自动排除。
        parts = re.split(r"\s+[—–|｜]\s+", heading, maxsplit=1)
        if len(parts) != 2:
            continue
        heading = parts[0].strip(" -—–_：:")
        if not heading or len(heading) > 80:
            continue
        if heading not in seen:
            seen.add(heading)
            out.append(heading)
    return out


def project_rotation_hint(round_name: str, qnum: int, resume: str = "") -> str:
    """给当前轮明确的项目轮换锚点，防止模型在第一项目上循环追问。"""
    projects = extract_resume_projects(resume)
    if len(projects) < 2 or qnum < 1:
        return ""
    # qnum 包含开场白。项目不是全场默认入口，只在明确的项目阶段给模型轮换锚点。
    # 一面先完成概念和场景热身，再在第 7～11 次发言进入项目；二面保留原来的前置项目段。
    windows = {"一面": (7, 11), "二面": (2, 7)}
    start, end = windows.get(round_name, windows["一面"])
    if qnum < start:
        return (
            "【项目延后硬约束】当前还在项目前的必考阶段。即使候选人提到简历项目，"
            "也只做一句承接，继续完成当前规定的概念题或场景题，不要展开项目深挖。"
        )
    phase_slots = end - start + 1
    offset = qnum - start
    if offset >= phase_slots:
        # 只在刚离开项目阶段的第一个回合提醒一次；之后不再反复提“项目”，避免
        # 概念题、场景题和代码阶段被一个否定式项目提示持续吸引。
        if qnum == end + 1:
            return (
                f"【项目覆盖硬约束】本场已安排覆盖：{'、'.join(projects)}。项目阶段已结束，"
                "不要回到第一个项目重复追问，按本场流程推进后续阶段。"
            )
        return ""
    # 尽量均匀分配项目槽位：两项目一面为 3+2，三项目为 2+2+1；更多项目仍保证轮换。
    index = min(len(projects) - 1, (offset * len(projects)) // phase_slots)
    current = projects[index]
    previous = projects[:index]
    upcoming = projects[index + 1:]
    hint = (
        f"【项目轮换调度｜仅供你执行】简历识别到 {len(projects)} 个项目：{'、'.join(projects)}。"
        f"当前项目阶段优先问《{current}》，本项目最多连续追问 3 次；"
    )
    if previous:
        hint += f"已经覆盖过{'、'.join(previous)}，除非候选人主动引用，不要切回它。"
    if upcoming:
        hint += f"项目阶段剩余项目为{'、'.join(upcoming)}，到边界必须自然过渡过去。"
    return hint

