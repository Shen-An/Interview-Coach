def interview_material_kinds(round_name: str, qnum: int) -> tuple[str, ...] | None:
    """返回本回合动态尾块允许使用的知识库类别。

    这是素材消费过滤，不改变整场 system 的选材，也不影响独立 QA 的检索。对一面的开场和
    收尾返回空元组表示不追加素材；返回 None 表示其他轮次不限制类别。
    """
    if round_name == "一面":
        if qnum in (2, 3, 12, 13):
            return ("questions",)
        if qnum in (4, 5, 6, 14, 15, 16):
            return ("scenarios",)
        if qnum in (17, 18):
            return ("coding",)
        if qnum in (1, 19):
            return ()
        return ()
    return None


def stage_hint(round_name: str, qnum: int) -> str:
    """qnum = 本次即将生成的面试官回合（开场白为第 1 回合）。返回只给面试官看的进度提示。"""
    stages = _STAGES.get(round_name, _STAGES["一面"])
    idx = next(i for i, (limit, _) in enumerate(stages) if qnum <= limit)
    cur = stages[idx][1]
    nxt = stages[idx + 1][1] if idx + 1 < len(stages) else ""
    left = stages[idx][0] - qnum
    tip = f"【进度提示，候选人不可见】这是你的第 {qnum} 次发言，当前阶段：「{cur}」。"
    if left == 0 and nxt:
        tip += f"该收尾当前话题了，用一句话过渡到「{nxt}」。"
    elif 0 < left <= 2 and nxt:
        tip += f"再问 {left} 个左右就该收掉当前话题，推进到「{nxt}」。"
    tip += "候选人回答很长时只能在当前题型内做一次必要追问；不得提前开启后续题型，也不得砍掉概念、场景或代码阶段。"
    return tip + question_type_hint(round_name, qnum)


def _intel_catalog(intel: str) -> str:
    """把情报里每节的标题＋主题行抽成目录。长上下文里模型靠它定位，
    相当于翻目录而不是从头读——但不用付一次工具往返的时间。"""
    lines = []
    for part in re.split(r"^## ", intel, flags=re.M)[1:]:
        head, _, body = part.partition("\n")
        topic = ""
        for ln in body.strip().splitlines():
            if ln.strip():
                m = re.match(r"\s*主题[:：]\s*(.+)", ln)
                if m:
                    topic = m.group(1).strip()
                break                      # 主题行必须是正文第一行，不往下找
        lines.append(f"- {head.strip()}" + (f"：{topic}" if topic else ""))
    return "\n".join(lines)


def _intel_body(intel: str, limit: int) -> tuple[str, int]:
    """取最近的若干小节全文，返回 (正文, 被省略的节数)。
    只在 `## ` 边界切，绝不把一节劈成半截。"""
    if len(intel) <= limit:
        return intel, 0
    cut = intel.rfind("\n## ", 0, limit)
    if cut <= 0:                     # 连一节都放不下，就整节给出去，宁可超一点
        nxt = intel.find("\n## ", 1)
        return (intel if nxt < 0 else intel[:nxt]), 0
    dropped = intel.count("\n## ", cut)
    return intel[:cut].rstrip(), dropped


# ---------------- 素材注入（题库 + 情报，同一个检索池） ----------------
_sel_cache: dict = {}


def select_wiki(round_name: str, company_style: str, resume: str, level: str) -> tuple:
    """整场面试选一次素材，返回 (store, {类别: [条目]})。题库条目和情报条目都在里面，
    各自带 space 字段，渲染时分成两块。

    每轮都会被调到（要算出字节相同的 system 才吃得到前缀缓存），所以按
    (语料版本 / 轮次 / 风格 / 身份 / 简历) 记忆，真正打分只发生第一次。"""
    store = retrieval.load(KB_DIR / "compiled", KB_DIR)
    if not store["items"]:
        return store, {}
    key = (store["newest"], store["total"], round_name, company_style, level, resume)
    if key not in _sel_cache:
        if len(_sel_cache) > 8:            # 单用户本地应用，几条足够，满了整体丢
            _sel_cache.clear()
        _sel_cache[key] = retrieval.select(
            store, resume=resume, round_name=round_name, style=company_style, level=level)
    return store, _sel_cache[key]


def turn_wiki(round_name: str, company_style: str, resume: str, level: str,
              recent: str, kinds: tuple[str, ...] | None = None) -> str:
    """每轮的素材补充，跟 stage_hint 一起挂进动态尾块。
    只给没进 system 的条目，免得同一条在提示词里出现两遍。"""
    store, sel = select_wiki(round_name, company_style, resume, level)
    if not store["items"]:
        return ""
    used = {it["id"] for items in sel.values() for it in items}
    picked = retrieval.select_turn(store, recent=recent, used_ids=used,
                                   style=company_style, level=level, kinds=kinds)
    return retrieval.render_turn(picked)



def _intel_by_time() -> str:
    """按时间注入的老路：目录全给，正文按字数只给最近的一段。
    数据目录里只有手写或旧版 UPDATES.md、没有 compiled/ 产物时还得靠它。"""
    intel = _read("UPDATES.md")[: kb.MAX_UPDATES_CHARS]
    if not intel.strip():
        return ""
    catalog = _intel_catalog(intel)
    body, dropped = _intel_body(intel, kb.INTEL_BODY_CHARS)
    tail = (
        f"\n（以上是最近的全文；目录里更早的 {dropped} 节只有摘要，需要细节就顺着摘要的关键词问，别编造具体数字。）\n"
        if dropped else ""
    )
    return ("\n<最新面经情报（时效性最强，出题优先参考；越靠前越新）>\n"
            f"目录（全部条目，先看这里定位）：\n{catalog}\n\n"
            f"正文（最近的部分，含细节）：\n{body}{tail}</最新面经情报>\n")



